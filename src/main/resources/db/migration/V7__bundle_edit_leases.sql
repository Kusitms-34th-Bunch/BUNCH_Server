CREATE TABLE bundle_edit_leases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bundle_id BIGINT NOT NULL REFERENCES bundles(id) ON DELETE CASCADE,
    target VARCHAR(64) NOT NULL,
    member_id BIGINT NOT NULL REFERENCES members(id),
    session_id VARCHAR(36) NOT NULL,
    screen_id VARCHAR(120) NOT NULL,
    connection_id VARCHAR(255) NOT NULL,
    token UUID NOT NULL,
    version BIGINT NOT NULL,
    last_heartbeat_at TIMESTAMP WITH TIME ZONE NOT NULL,
    released_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_bundle_edit_lease_target UNIQUE (bundle_id, target),
    CONSTRAINT ck_bundle_edit_lease_version CHECK (version > 0),
    CONSTRAINT ck_bundle_edit_lease_target CHECK (
        target IN ('TITLE', 'DATE') OR target ~ '^PHOTO:[1-9][0-9]*$'
    )
);

CREATE INDEX ix_bundle_edit_leases_bundle ON bundle_edit_leases(bundle_id);
CREATE INDEX ix_bundle_edit_leases_connection ON bundle_edit_leases(connection_id);
