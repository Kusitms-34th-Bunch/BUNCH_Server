CREATE TABLE social_content_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_bunch_id BIGINT NOT NULL REFERENCES bunches(id) ON DELETE CASCADE,
    target_kind VARCHAR(16) NOT NULL CHECK (target_kind IN ('BUNDLE', 'COMMENT')),
    target_id BIGINT NOT NULL CHECK (target_id > 0),
    reported_by_member_id BIGINT NOT NULL REFERENCES members(id) ON DELETE RESTRICT,
    reason VARCHAR(32) NOT NULL CHECK (
        reason IN ('SPAM', 'INAPPROPRIATE', 'HARASSMENT', 'PERSONAL_INFORMATION', 'OTHER')
    ),
    detail TEXT,
    status VARCHAR(16) NOT NULL DEFAULT 'RECEIVED' CHECK (
        status IN ('RECEIVED', 'REVIEWING', 'ACTIONED', 'DISMISSED')
    ),
    created_at TIMESTAMPTZ NOT NULL,
    window_started_at TIMESTAMPTZ NOT NULL,
    reviewed_at TIMESTAMPTZ
);

CREATE INDEX ix_social_content_report_window
    ON social_content_reports (reporter_bunch_id, target_kind, target_id, window_started_at DESC, id DESC);
