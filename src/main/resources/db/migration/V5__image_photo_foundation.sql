DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM members
        WHERE (image_public_id IS NULL) <> (image_url IS NULL)
    ) THEN
        RAISE EXCEPTION 'Legacy member profile image must contain both public ID and URL';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM bunches
        WHERE (image_public_id IS NULL) <> (image_url IS NULL)
    ) THEN
        RAISE EXCEPTION 'Legacy bunch profile image must contain both public ID and URL';
    END IF;

    IF EXISTS (
        SELECT legacy.public_id
        FROM (
            SELECT image_public_id AS public_id, image_url::TEXT AS url
            FROM members
            WHERE image_public_id IS NOT NULL
            UNION ALL
            SELECT image_public_id AS public_id, image_url::TEXT AS url
            FROM bunches
            WHERE image_public_id IS NOT NULL
        ) AS legacy
        GROUP BY legacy.public_id
        HAVING COUNT(DISTINCT legacy.url) > 1
    ) THEN
        RAISE EXCEPTION 'Legacy profile image URLs must agree for each public ID';
    END IF;
END
$$;

CREATE TABLE image_assets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id VARCHAR(255) NOT NULL,
    url TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_image_asset_public_id UNIQUE (public_id)
);

INSERT INTO image_assets (public_id, url, created_at)
SELECT legacy.public_id, legacy.url, CURRENT_TIMESTAMP
FROM (
    SELECT image_public_id AS public_id, image_url::TEXT AS url
    FROM members
    WHERE image_public_id IS NOT NULL
    UNION
    SELECT image_public_id AS public_id, image_url::TEXT AS url
    FROM bunches
    WHERE image_public_id IS NOT NULL
) AS legacy;

ALTER TABLE members
    ADD COLUMN profile_image_asset_id BIGINT;

ALTER TABLE bunches
    ADD COLUMN profile_image_asset_id BIGINT;

UPDATE members AS member
SET profile_image_asset_id = asset.id
FROM image_assets AS asset
WHERE member.image_public_id = asset.public_id;

UPDATE bunches AS bunch
SET profile_image_asset_id = asset.id
FROM image_assets AS asset
WHERE bunch.image_public_id = asset.public_id;

ALTER TABLE members
    ADD CONSTRAINT fk_member_profile_image_asset
        FOREIGN KEY (profile_image_asset_id)
        REFERENCES image_assets(id)
        ON DELETE RESTRICT;

ALTER TABLE bunches
    ADD CONSTRAINT fk_bunch_profile_image_asset
        FOREIGN KEY (profile_image_asset_id)
        REFERENCES image_assets(id)
        ON DELETE RESTRICT;

ALTER TABLE members
    DROP COLUMN image_public_id,
    DROP COLUMN image_url;

ALTER TABLE bunches
    DROP COLUMN image_public_id,
    DROP COLUMN image_url;

CREATE TABLE photos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bunch_id BIGINT NOT NULL REFERENCES bunches(id) ON DELETE CASCADE,
    image_asset_id BIGINT NOT NULL REFERENCES image_assets(id) ON DELETE RESTRICT,
    file_hash VARCHAR(64) NOT NULL,
    processing_status VARCHAR(16) NOT NULL,
    captured_date DATE,
    captured_time TIME,
    date_source VARCHAR(16) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_photo_file_hash_sha256 CHECK (file_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_photo_processing_status CHECK (processing_status IN ('PENDING', 'READY', 'FAILED')),
    CONSTRAINT ck_photo_date_source CHECK (
        (date_source = 'UNKNOWN' AND captured_date IS NULL AND captured_time IS NULL)
        OR
        (date_source IN ('EXIF', 'USER') AND captured_date IS NOT NULL)
    ),
    CONSTRAINT uk_photo_bunch_file_hash UNIQUE (bunch_id, file_hash)
);

CREATE TABLE photo_uploaders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    photo_id BIGINT NOT NULL REFERENCES photos(id) ON DELETE CASCADE,
    member_id BIGINT NOT NULL REFERENCES members(id),
    upload_batch_id UUID NOT NULL,
    uploaded_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_photo_uploader UNIQUE (photo_id, member_id)
);

CREATE INDEX ix_members_profile_image_asset_id
    ON members(profile_image_asset_id);

CREATE INDEX ix_bunches_profile_image_asset_id
    ON bunches(profile_image_asset_id);

CREATE INDEX ix_photos_image_asset_id
    ON photos(image_asset_id);

CREATE INDEX ix_photo_uploaders_member_id
    ON photo_uploaders(member_id);
