-- The recommended bundles of the new combination (recommended bundle specification 10): the result of the calculation
-- of a day, kept until the day is calculated again. They are not the bundles a member makes (bundles), and they are
-- not the old recommended bundles (bundle_candidates), which are kept until the new ones take their place.
--
-- A day that is calculated again has its recommended bundles replaced (10-3): the ones with the same stable_key are
-- kept with their id, created_at and visible_from, the ones that are no more are deleted and the new ones are added.
-- A bundle that disappears is deleted and not recorded, so there is no status column.
CREATE TABLE recommended_bundles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bunch_id BIGINT NOT NULL REFERENCES bunches(id) ON DELETE CASCADE,
    -- The day the bundle belongs to, which starts at 05:00 on the local clock (3-1).
    day_key DATE NOT NULL,
    -- The hash of the bunch, the day and the numbers of all the photos of the bundle (10-3).
    stable_key VARCHAR(64) NOT NULL,
    kind VARCHAR(16) NOT NULL,
    event_type VARCHAR(32),
    established_by VARCHAR(16),
    activity VARCHAR(32),
    -- The number of the part of a day that was cut for being over the limit of photos (7-7), from 1.
    sub_index INTEGER,
    title VARCHAR(100) NOT NULL,
    start_at TIMESTAMP WITH TIME ZONE NOT NULL,
    end_at TIMESTAMP WITH TIME ZONE NOT NULL,
    photo_count INTEGER NOT NULL,
    uploader_count INTEGER NOT NULL,
    has_group_photo BOOLEAN NOT NULL,
    -- How the bundle was made (11). It is kept to be read, not to be calculated from.
    rule_trace JSONB NOT NULL,
    -- The bundle is shown from this time (10-4).
    visible_from TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_recommended_bundles_bunch_stable_key UNIQUE (bunch_id, stable_key),
    CONSTRAINT ck_recommended_bundles_kind CHECK (kind IN ('EVENT', 'GENERAL')),
    CONSTRAINT ck_recommended_bundles_event_type CHECK (
        event_type IS NULL OR event_type IN (
            'BIRTHDAY', 'GRADUATION', 'YEAR_END', 'WEDDING', 'CONCERT', 'SPORTS_VIEWING', 'COMPETITION',
            'TRAVEL', 'CAMPING', 'HOLIDAY', 'THEME_PARK'
        )
    ),
    CONSTRAINT ck_recommended_bundles_established_by CHECK (
        established_by IS NULL OR established_by IN ('STRONG', 'SUPPORT', 'DATE_BOOST')
    ),
    -- An event bundle has an event type and what made it stand, a general bundle has neither (4-5).
    CONSTRAINT ck_recommended_bundles_kind_fields CHECK (
        (kind = 'EVENT' AND event_type IS NOT NULL AND established_by IS NOT NULL)
        OR (kind = 'GENERAL' AND event_type IS NULL AND established_by IS NULL)
    ),
    CONSTRAINT ck_recommended_bundles_activity CHECK (
        activity IS NULL OR activity IN (
            'MEAL', 'CAFE', 'DRINKS', 'CELEBRATION', 'STUDY_WORK', 'HOME', 'WALK', 'SHOW_EXHIBITION', 'SPORTS',
            'SHOPPING', 'OTHER', 'SIGHTSEEING', 'OUTDOOR', 'TRANSIT', 'UNKNOWN'
        )
    ),
    CONSTRAINT ck_recommended_bundles_sub_index CHECK (sub_index IS NULL OR sub_index >= 1),
    CONSTRAINT ck_recommended_bundles_time CHECK (end_at >= start_at),
    CONSTRAINT ck_recommended_bundles_counts CHECK (photo_count >= 0 AND uploader_count >= 0),
    CONSTRAINT ck_recommended_bundles_title_not_blank CHECK (btrim(title) <> ''),
    CONSTRAINT ck_recommended_bundles_title_no_linebreak CHECK (
        position(E'\n' IN title) = 0
        AND position(E'\r' IN title) = 0
    ),
    CONSTRAINT ck_recommended_bundles_timestamps CHECK (updated_at >= created_at)
);

-- The bundles of a day are read and replaced together (10-3), and the list is read by bunch and by the time shown.
CREATE INDEX ix_recommended_bundles_bunch_day
    ON recommended_bundles(bunch_id, day_key);

CREATE INDEX ix_recommended_bundles_bunch_visible_from
    ON recommended_bundles(bunch_id, visible_from);

-- Every photo of a bundle, the ones the card does not show too. The photos on the card have a position, from 1, in the
-- order they are shown in, and the one with the position 1 is the cover (8-6). A photo is in one bundle only (7-10).
CREATE TABLE recommended_bundle_photos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bundle_id BIGINT NOT NULL REFERENCES recommended_bundles(id) ON DELETE CASCADE,
    photo_id BIGINT NOT NULL REFERENCES photos(id) ON DELETE CASCADE,
    role VARCHAR(24) NOT NULL,
    card_position INTEGER,
    CONSTRAINT uk_recommended_bundle_photos_photo UNIQUE (photo_id),
    CONSTRAINT ck_recommended_bundle_photos_role CHECK (
        role IN ('CLUE', 'RELATED', 'GENERAL', 'ATTACHED_DATE_ONLY')
    ),
    CONSTRAINT ck_recommended_bundle_photos_position CHECK (card_position IS NULL OR card_position >= 1)
);

-- A place on the card is used once in a bundle.
CREATE UNIQUE INDEX uk_recommended_bundle_photos_position
    ON recommended_bundle_photos(bundle_id, card_position)
    WHERE card_position IS NOT NULL;

CREATE INDEX ix_recommended_bundle_photos_bundle_id
    ON recommended_bundle_photos(bundle_id);

-- The days to calculate again (10-1, 10-2). A change of the photos puts the day here to be calculated at due_at, and
-- another change before that moves due_at later, so the day is calculated once, after the last change. A day is
-- calculated at most once at a time.
CREATE TABLE recommended_bundle_recalc_queue (
    bunch_id BIGINT NOT NULL REFERENCES bunches(id) ON DELETE CASCADE,
    day_key DATE NOT NULL,
    due_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (bunch_id, day_key)
);

CREATE INDEX ix_recommended_bundle_recalc_queue_due_at
    ON recommended_bundle_recalc_queue(due_at);
