CREATE TABLE pinned_places (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bunch_id BIGINT NOT NULL REFERENCES bunches(id) ON DELETE CASCADE,
    provider VARCHAR(32) NOT NULL,
    external_id VARCHAR(128) NOT NULL,
    name TEXT NOT NULL,
    address TEXT NOT NULL,
    source_type VARCHAR(16) NOT NULL,
    source_bundle_id BIGINT REFERENCES bundles(id) ON DELETE SET NULL,
    source_location_id BIGINT REFERENCES bundle_locations(id) ON DELETE SET NULL,
    source_advertisement_id BIGINT,
    pinned_by_member_id BIGINT REFERENCES members(id) ON DELETE SET NULL,
    pinned_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_pinned_place_key UNIQUE (bunch_id, provider, external_id),
    CONSTRAINT ck_pinned_place_provider CHECK (provider ~ '^[a-z0-9_-]{1,32}$'),
    CONSTRAINT ck_pinned_place_external_id CHECK (btrim(external_id) <> '' AND external_id = btrim(external_id)),
    CONSTRAINT ck_pinned_place_name CHECK (btrim(name) <> ''),
    CONSTRAINT ck_pinned_place_address CHECK (btrim(address) <> ''),
    CONSTRAINT ck_pinned_place_source CHECK (
        (source_type = 'BUNDLE' AND source_advertisement_id IS NULL) OR
        (source_type = 'ADVERTISEMENT' AND source_bundle_id IS NULL AND source_location_id IS NULL)
    ),
    CONSTRAINT ck_pinned_place_advertisement CHECK (source_advertisement_id IS NULL OR source_advertisement_id > 0)
);

CREATE INDEX ix_pinned_place_source_location ON pinned_places(source_bundle_id, source_location_id)
    WHERE source_location_id IS NOT NULL;
