CREATE TABLE async_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_type VARCHAR(64) NOT NULL,
    target_key VARCHAR(255) NOT NULL,
    status VARCHAR(16) NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL,
    lease_until TIMESTAMP WITH TIME ZONE,
    last_error_code VARCHAR(64),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_async_job_status CHECK (status IN ('PENDING', 'RUNNING', 'SUCCEEDED', 'FAILED')),
    CONSTRAINT ck_async_job_attempts CHECK (attempts >= 0),
    -- Only a running job holds a lease.
    CONSTRAINT ck_async_job_lease CHECK ((status = 'RUNNING') = (lease_until IS NOT NULL))
);

-- A job of one type for one target exists only once while it is unfinished.
CREATE UNIQUE INDEX uk_async_job_active
    ON async_jobs(job_type, target_key)
    WHERE status IN ('PENDING', 'RUNNING');

CREATE INDEX ix_async_jobs_due
    ON async_jobs(next_attempt_at, id)
    WHERE status = 'PENDING';

CREATE INDEX ix_async_jobs_lease
    ON async_jobs(lease_until)
    WHERE status = 'RUNNING';
