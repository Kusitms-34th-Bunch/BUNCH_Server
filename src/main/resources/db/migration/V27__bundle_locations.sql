ALTER TABLE bundles
    ADD COLUMN location_version BIGINT NOT NULL DEFAULT 0,
    ADD CONSTRAINT ck_bundle_location_version CHECK (location_version >= 0);

CREATE TABLE bundle_locations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bundle_id BIGINT NOT NULL REFERENCES bundles(id) ON DELETE CASCADE,
    provider VARCHAR(32) NOT NULL,
    external_id VARCHAR(128) NOT NULL,
    name TEXT NOT NULL,
    address TEXT NOT NULL,
    position INTEGER NOT NULL,
    CONSTRAINT ck_bundle_location_provider CHECK (provider ~ '^[a-z0-9_-]{1,32}$'),
    CONSTRAINT ck_bundle_location_external_id CHECK (btrim(external_id) <> '' AND external_id = btrim(external_id)),
    CONSTRAINT ck_bundle_location_name CHECK (btrim(name) <> ''),
    CONSTRAINT ck_bundle_location_address CHECK (btrim(address) <> ''),
    CONSTRAINT ck_bundle_location_position CHECK (position BETWEEN 0 AND 2),
    CONSTRAINT uk_bundle_location_key UNIQUE (bundle_id, provider, external_id),
    CONSTRAINT uk_bundle_location_position UNIQUE (bundle_id, position) DEFERRABLE INITIALLY DEFERRED
);

ALTER TABLE bundle_edit_leases DROP CONSTRAINT ck_bundle_edit_lease_target;
ALTER TABLE bundle_edit_leases ADD CONSTRAINT ck_bundle_edit_lease_target CHECK (
    target IN ('TITLE', 'DATE', 'LOCATION') OR target ~ '^PHOTO:[1-9][0-9]*$'
);
