CREATE TABLE social_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bundle_id BIGINT NOT NULL REFERENCES bundles(id) ON DELETE CASCADE,
    author_member_id BIGINT NOT NULL REFERENCES members(id) ON DELETE RESTRICT,
    acting_bunch_id BIGINT REFERENCES bunches(id) ON DELETE SET NULL,
    badge_name VARCHAR(120) NOT NULL,
    badge_character_type VARCHAR(16) NOT NULL,
    parent_id BIGINT,
    content TEXT NOT NULL,
    request_key UUID NOT NULL,
    fingerprint VARCHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    deleted_at TIMESTAMPTZ,
    CONSTRAINT uk_social_comment_bundle_id UNIQUE (bundle_id, id),
    CONSTRAINT fk_social_comment_parent FOREIGN KEY (bundle_id, parent_id)
        REFERENCES social_comments(bundle_id, id) ON DELETE CASCADE,
    CONSTRAINT uk_social_comment_request UNIQUE (author_member_id, acting_bunch_id, bundle_id, request_key),
    CONSTRAINT ck_social_comment_not_self_parent CHECK (parent_id IS NULL OR parent_id <> id),
    CONSTRAINT ck_social_comment_content CHECK (
        (deleted_at IS NULL AND length(btrim(content)) > 0) OR (deleted_at IS NOT NULL AND content = '')
    ),
    CONSTRAINT ck_social_comment_deleted_at CHECK (deleted_at IS NULL OR deleted_at >= created_at)
);

CREATE INDEX ix_social_comments_bundle_parent_created_id
    ON social_comments(bundle_id, parent_id, created_at, id);
CREATE INDEX ix_social_comments_parent_id ON social_comments(parent_id);
CREATE INDEX ix_social_comments_acting_bunch ON social_comments(acting_bunch_id);
CREATE INDEX ix_social_comments_author ON social_comments(author_member_id);

CREATE FUNCTION validate_social_comment_parent() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.parent_id IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM social_comments parent
        WHERE parent.id = NEW.parent_id AND parent.bundle_id = NEW.bundle_id AND parent.parent_id IS NULL
    ) THEN
        RAISE EXCEPTION 'reply parent must be a root in the same bundle' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER social_comment_parent_depth BEFORE INSERT OR UPDATE OF parent_id, bundle_id
    ON social_comments FOR EACH ROW EXECUTE FUNCTION validate_social_comment_parent();
