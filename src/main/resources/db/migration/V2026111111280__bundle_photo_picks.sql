-- Picks belong to a bundle photo and one of that same bundle's participants.
ALTER TABLE bundle_photos ADD CONSTRAINT uk_bundle_photo_bundle_id UNIQUE (bundle_id, id);

CREATE TABLE bundle_photo_picks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bundle_id BIGINT NOT NULL,
    bundle_photo_id BIGINT NOT NULL,
    member_id BIGINT NOT NULL,
    picked BOOLEAN NOT NULL,
    version BIGINT NOT NULL CHECK (version >= 0),
    CONSTRAINT uk_bundle_photo_pick UNIQUE (bundle_photo_id, member_id),
    CONSTRAINT fk_bundle_photo_pick_photo FOREIGN KEY (bundle_id, bundle_photo_id)
        REFERENCES bundle_photos(bundle_id, id) ON DELETE CASCADE,
    CONSTRAINT fk_bundle_photo_pick_participant FOREIGN KEY (bundle_id, member_id)
        REFERENCES bundle_participants(bundle_id, member_id) ON DELETE CASCADE
);

CREATE INDEX ix_bundle_photo_picks_bundle_member ON bundle_photo_picks(bundle_id, member_id);
