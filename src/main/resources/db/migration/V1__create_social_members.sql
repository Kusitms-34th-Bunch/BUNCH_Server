CREATE TABLE members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255),
    role VARCHAR(32) NOT NULL
);
CREATE TABLE external_identity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES members(id),
    provider VARCHAR(32) NOT NULL CHECK (provider IN ('APPLE', 'GOOGLE', 'KAKAO')),
    provider_subject VARCHAR(255) NOT NULL,
    email_at_link_time VARCHAR(255),
    CONSTRAINT uk_identity_provider_subject UNIQUE (provider, provider_subject)
);
CREATE INDEX ix_identity_member ON external_identity(member_id);
