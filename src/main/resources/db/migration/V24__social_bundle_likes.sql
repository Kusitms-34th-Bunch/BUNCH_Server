CREATE TABLE social_bundle_likes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bunch_id BIGINT NOT NULL REFERENCES bunches(id) ON DELETE CASCADE,
    bundle_id BIGINT NOT NULL REFERENCES bundles(id) ON DELETE CASCADE,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    first_liked_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_social_bundle_like UNIQUE (bunch_id, bundle_id)
);

-- Inactive rows preserve the first-like fact independently of inbox/job retention.
CREATE INDEX ix_social_bundle_likes_active_bundle
    ON social_bundle_likes(bundle_id, bunch_id) WHERE active;
