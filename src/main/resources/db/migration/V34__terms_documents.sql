-- Terms text served to the app (my page 7.4.1~7.4.2, sign up 1.3.2).
-- No text is seeded here. The approved text is added by a later migration together with its version.
CREATE TABLE terms_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(32) NOT NULL CHECK (type IN ('SERVICE', 'PRIVACY')),
    version VARCHAR(100) NOT NULL,
    effective_date DATE NOT NULL,
    clauses JSONB NOT NULL,
    CONSTRAINT uk_terms_document UNIQUE (type, version),
    CONSTRAINT ck_terms_document_clauses CHECK (
        jsonb_typeof(clauses) = 'array' AND jsonb_array_length(clauses) > 0
    )
);
