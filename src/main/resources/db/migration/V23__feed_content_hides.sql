-- NULL reporter = DB-operated global hide; non-NULL = only this reporter bunch cannot see it.
-- Targets are polymorphic identifiers, not placeholder future-domain tables.
CREATE TABLE feed_content_hides (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_kind VARCHAR(16) NOT NULL,
    target_id BIGINT NOT NULL,
    reporter_bunch_id BIGINT REFERENCES bunches(id) ON DELETE CASCADE,
    reason TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_feed_hide_kind CHECK (target_kind IN ('BUNCH', 'BUNDLE', 'COMMENT')),
    CONSTRAINT ck_feed_hide_target CHECK (target_id > 0),
    CONSTRAINT ck_feed_hide_reason CHECK (btrim(reason) <> ''),
    CONSTRAINT uk_feed_hide_scope UNIQUE NULLS NOT DISTINCT (target_kind, target_id, reporter_bunch_id)
);

CREATE INDEX ix_feed_hides_reporter ON feed_content_hides(reporter_bunch_id)
    WHERE reporter_bunch_id IS NOT NULL;
