CREATE TABLE feed_advertisements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (btrim(name) <> ''),
    introduction TEXT NOT NULL CHECK (btrim(introduction) <> ''),
    photo_url TEXT NOT NULL CHECK (photo_url ~ '^https?://[^[:space:]]+$'),
    tags JSONB NOT NULL DEFAULT '[]'::jsonb,
    external_link TEXT CHECK (external_link IS NULL OR external_link ~ '^https?://[^[:space:]]+$'),
    place_provider VARCHAR(32) NOT NULL CHECK (place_provider ~ '^[a-z0-9_-]{1,32}$'),
    place_external_id VARCHAR(128) NOT NULL CHECK (
        btrim(place_external_id) <> '' AND place_external_id = btrim(place_external_id)
    ),
    place_name TEXT NOT NULL CHECK (btrim(place_name) <> ''),
    place_address TEXT NOT NULL CHECK (btrim(place_address) <> ''),
    active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_advertisement_tags CHECK (
        jsonb_typeof(tags) = 'array' AND NOT jsonb_path_exists(tags, '$[*] ? (@.type() != "string")')
    )
);

CREATE INDEX ix_advertisements_active ON feed_advertisements (id) WHERE active;

CREATE TABLE feed_advertisement_hides (
    member_id BIGINT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
    advertisement_id BIGINT NOT NULL REFERENCES feed_advertisements(id) ON DELETE CASCADE,
    hidden_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (member_id, advertisement_id)
);
