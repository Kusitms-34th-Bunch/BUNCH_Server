CREATE TABLE bunches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) COLLATE "C" NOT NULL UNIQUE,
    introduction TEXT NOT NULL,
    visibility VARCHAR(16) NOT NULL CHECK (visibility IN ('PUBLIC', 'PRIVATE')),
    character_type VARCHAR(16) NOT NULL CHECK (character_type IN ('TYPE_1', 'TYPE_2', 'TYPE_3', 'TYPE_4')),
    image_public_id VARCHAR(255),
    image_url TEXT,
    created_by BIGINT NOT NULL REFERENCES members(id),
    creation_request_key UUID NOT NULL,
    creation_fingerprint VARCHAR(64) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_bunch_creation_request UNIQUE (created_by, creation_request_key)
);

CREATE TABLE bunch_memberships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bunch_id BIGINT NOT NULL REFERENCES bunches(id) ON DELETE CASCADE,
    member_id BIGINT NOT NULL REFERENCES members(id),
    role VARCHAR(16) NOT NULL CHECK (role IN ('OWNER', 'MEMBER')),
    status VARCHAR(16) NOT NULL CHECK (status IN ('ACTIVE', 'LEFT', 'REMOVED')),
    joined_at TIMESTAMP WITH TIME ZONE NOT NULL,
    role_granted_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_used_at TIMESTAMP WITH TIME ZONE NOT NULL,
    -- Successful join keys and canonical invitation fingerprints belong to their result.
    -- Several keys may resolve to ALREADY_MEMBER without creating another membership.
    join_requests JSONB NOT NULL DEFAULT '{}'::jsonb,
    CHECK (jsonb_typeof(join_requests) = 'object')
);
CREATE UNIQUE INDEX uk_bunch_active_membership ON bunch_memberships(bunch_id, member_id) WHERE status = 'ACTIVE';
CREATE INDEX ix_membership_recent ON bunch_memberships(member_id, last_used_at DESC, id DESC) WHERE status = 'ACTIVE';

CREATE TABLE bunch_invitations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bunch_id BIGINT NOT NULL REFERENCES bunches(id) ON DELETE CASCADE,
    issuer_member_id BIGINT NOT NULL REFERENCES members(id),
    token VARCHAR(43) COLLATE "C" NOT NULL UNIQUE,
    code VARCHAR(8) COLLATE "C" NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITH TIME ZONE,
    CHECK (expires_at > created_at)
);
CREATE UNIQUE INDEX uk_bunch_nonrevoked_invitation ON bunch_invitations(bunch_id) WHERE revoked_at IS NULL;

CREATE TABLE bunch_join_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bunch_id BIGINT NOT NULL REFERENCES bunches(id) ON DELETE CASCADE,
    joined_membership_id BIGINT NOT NULL REFERENCES bunch_memberships(id) ON DELETE CASCADE,
    recipient_member_id BIGINT NOT NULL REFERENCES members(id),
    joined_member_id BIGINT NOT NULL REFERENCES members(id),
    type VARCHAR(32) NOT NULL DEFAULT 'NEW_MEMBER' CHECK (type = 'NEW_MEMBER'),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_join_notification_recipient UNIQUE (joined_membership_id, recipient_member_id),
    CHECK (recipient_member_id <> joined_member_id)
);
