-- Recommended bundle candidates (photo box 4.2.9 rule 2). A candidate that disappears is deleted and not recorded,
-- so there is no status column.
CREATE TABLE bundle_candidates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bunch_id BIGINT NOT NULL REFERENCES bunches(id) ON DELETE CASCADE,
    start_date DATE NOT NULL,
    end_date DATE,
    title VARCHAR(60) NOT NULL,
    title_sentence_key VARCHAR(64),
    last_photo_added_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_candidate_dates CHECK (end_date IS NULL OR end_date > start_date),
    CONSTRAINT ck_candidate_title_not_blank CHECK (btrim(title) <> ''),
    CONSTRAINT ck_candidate_title_no_linebreak CHECK (
        position(E'\n' IN title) = 0
        AND position(E'\r' IN title) = 0
    ),
    CONSTRAINT ck_candidate_timestamps CHECK (updated_at >= created_at)
);

CREATE INDEX ix_bundle_candidates_bunch_start_id
    ON bundle_candidates(bunch_id, start_date, id);

-- Every photo of the group is kept. Only the photos chosen for the card (at most 10) have a position, which is
-- the order they are shown in.
CREATE TABLE candidate_photos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id BIGINT NOT NULL REFERENCES bundle_candidates(id) ON DELETE CASCADE,
    photo_id BIGINT NOT NULL REFERENCES photos(id) ON DELETE CASCADE,
    position INTEGER,
    CONSTRAINT uk_candidate_photo_candidate_photo UNIQUE (candidate_id, photo_id),
    CONSTRAINT ck_candidate_photo_position CHECK (position IS NULL OR position BETWEEN 1 AND 10)
);

CREATE INDEX ix_candidate_photos_photo_id
    ON candidate_photos(photo_id);

-- The dates changed while waiting for the 5 minutes without a change, so one recalculation runs after the last
-- change (4.2.9 rule 2).
CREATE TABLE recommendation_dirty_dates (
    bunch_id BIGINT NOT NULL REFERENCES bunches(id) ON DELETE CASCADE,
    captured_date DATE NOT NULL,
    changed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (bunch_id, captured_date)
);
