-- Access notices are independent of the bunch aggregate so a removed member can
-- still open the notice after the membership is ended. The action-request table
-- is owned by #49/V16 and is intentionally not created in this migration.
CREATE TABLE bunch_access_notices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_member_id BIGINT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
    bunch_id BIGINT NOT NULL,
    membership_id BIGINT NOT NULL,
    bunch_name VARCHAR(120) NOT NULL,
    character_type VARCHAR(16) NOT NULL CHECK (character_type IN ('TYPE_1', 'TYPE_2', 'TYPE_3', 'TYPE_4')),
    reason VARCHAR(16) NOT NULL CHECK (reason IN ('REMOVED', 'DELETED')),
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_bunch_access_notice_recipient_membership_reason
        UNIQUE (recipient_member_id, membership_id, reason),
    CONSTRAINT ck_bunch_access_notice_expiry CHECK (expires_at > occurred_at)
);

CREATE INDEX ix_bunch_access_notice_recipient_occurred
    ON bunch_access_notices(recipient_member_id, occurred_at DESC, id DESC);

CREATE INDEX ix_bunch_access_notice_expires
    ON bunch_access_notices(expires_at, id);
