CREATE TABLE bunch_follows (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    follower_bunch_id BIGINT NOT NULL REFERENCES bunches(id) ON DELETE CASCADE,
    followed_bunch_id BIGINT NOT NULL REFERENCES bunches(id) ON DELETE CASCADE,
    status VARCHAR(16) NOT NULL CHECK (status IN ('PENDING', 'APPROVED')),
    created_by_member_id BIGINT NOT NULL REFERENCES members(id) ON DELETE RESTRICT,
    approved_by_member_id BIGINT REFERENCES members(id) ON DELETE SET NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    approved_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_bunch_follow_pair UNIQUE (follower_bunch_id, followed_bunch_id),
    CONSTRAINT ck_bunch_follow_not_self CHECK (follower_bunch_id <> followed_bunch_id),
    CONSTRAINT ck_bunch_follow_approval CHECK (
        (status = 'PENDING' AND approved_at IS NULL)
        OR (status = 'APPROVED' AND approved_at IS NOT NULL)
    )
);

CREATE INDEX ix_bunch_follow_requests ON bunch_follows (followed_bunch_id, status, created_at DESC, id DESC);
CREATE INDEX ix_bunch_followers ON bunch_follows (followed_bunch_id, status, approved_at DESC, id DESC);
CREATE INDEX ix_bunch_following ON bunch_follows (follower_bunch_id, status, approved_at DESC, id DESC);

CREATE TABLE bunch_blocks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blocker_bunch_id BIGINT NOT NULL REFERENCES bunches(id) ON DELETE CASCADE,
    blocked_bunch_id BIGINT NOT NULL REFERENCES bunches(id) ON DELETE CASCADE,
    created_by_member_id BIGINT NOT NULL REFERENCES members(id) ON DELETE RESTRICT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_bunch_block_pair UNIQUE (blocker_bunch_id, blocked_bunch_id),
    CHECK (blocker_bunch_id <> blocked_bunch_id)
);
CREATE INDEX ix_bunch_blocks ON bunch_blocks (blocker_bunch_id, created_at DESC, id DESC);
CREATE INDEX ix_bunch_blocks_reverse ON bunch_blocks (blocked_bunch_id, blocker_bunch_id);

CREATE TABLE bunch_profile_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_bunch_id BIGINT NOT NULL REFERENCES bunches(id) ON DELETE CASCADE,
    target_bunch_id BIGINT NOT NULL REFERENCES bunches(id) ON DELETE CASCADE,
    reported_by_member_id BIGINT NOT NULL REFERENCES members(id) ON DELETE RESTRICT,
    reason VARCHAR(32) NOT NULL CHECK (reason IN ('SPAM', 'INAPPROPRIATE', 'HARASSMENT', 'PERSONAL_INFORMATION', 'OTHER')),
    detail TEXT,
    status VARCHAR(16) NOT NULL DEFAULT 'RECEIVED' CHECK (status IN ('RECEIVED', 'REVIEWING', 'ACTIONED', 'DISMISSED')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    reviewed_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_bunch_report_pair UNIQUE (reporter_bunch_id, target_bunch_id),
    CHECK (reporter_bunch_id <> target_bunch_id)
);
