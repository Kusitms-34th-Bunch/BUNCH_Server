CREATE TABLE bundles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bunch_id BIGINT NOT NULL REFERENCES bunches(id) ON DELETE CASCADE,
    created_by BIGINT NOT NULL REFERENCES members(id) ON DELETE RESTRICT,
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    title TEXT NOT NULL DEFAULT '',
    visibility VARCHAR(16),
    bundle_date DATE,
    revision BIGINT NOT NULL DEFAULT 0,
    title_version BIGINT NOT NULL DEFAULT 0,
    visibility_version BIGINT NOT NULL DEFAULT 0,
    date_version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    published_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_bundle_status CHECK (status IN ('DRAFT', 'PUBLISHED')),
    CONSTRAINT ck_bundle_visibility CHECK (visibility IS NULL OR visibility IN ('PUBLIC', 'PRIVATE')),
    CONSTRAINT ck_bundle_title_no_linebreak CHECK (
        position(E'\n' IN title) = 0
        AND position(E'\r' IN title) = 0
    ),
    CONSTRAINT ck_bundle_versions_nonnegative CHECK (
        revision >= 0
        AND title_version >= 0
        AND visibility_version >= 0
        AND date_version >= 0
    ),
    CONSTRAINT ck_bundle_timestamps CHECK (
        updated_at >= created_at
        AND (published_at IS NULL OR published_at >= created_at)
    )
);

CREATE INDEX ix_bundles_bunch_status_id
    ON bundles(bunch_id, status, id);

CREATE TABLE bundle_photos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bundle_id BIGINT NOT NULL REFERENCES bundles(id) ON DELETE CASCADE,
    photo_id BIGINT REFERENCES photos(id) ON DELETE SET NULL,
    image_asset_id BIGINT NOT NULL REFERENCES image_assets(id) ON DELETE RESTRICT,
    position INTEGER NOT NULL,
    added_by BIGINT NOT NULL REFERENCES members(id) ON DELETE RESTRICT,
    added_at TIMESTAMP WITH TIME ZONE NOT NULL,
    caption TEXT NOT NULL DEFAULT '',
    caption_version BIGINT NOT NULL DEFAULT 0,
    caption_updated_by BIGINT REFERENCES members(id) ON DELETE RESTRICT,
    caption_updated_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_bundle_photo_bundle_photo UNIQUE (bundle_id, photo_id),
    CONSTRAINT ck_bundle_photo_position_nonnegative CHECK (position >= 0),
    CONSTRAINT ck_bundle_photo_caption_version_nonnegative CHECK (caption_version >= 0),
    CONSTRAINT ck_bundle_photo_caption_editor CHECK (
        (caption_updated_by IS NULL AND caption_updated_at IS NULL)
        OR
        (caption_updated_by IS NOT NULL AND caption_updated_at IS NOT NULL)
    )
);

CREATE INDEX ix_bundle_photos_bundle_position_id
    ON bundle_photos(bundle_id, position, id);

CREATE INDEX ix_bundle_photos_photo_id
    ON bundle_photos(photo_id);

CREATE TABLE bundle_participants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bundle_id BIGINT NOT NULL REFERENCES bundles(id) ON DELETE CASCADE,
    member_id BIGINT NOT NULL REFERENCES members(id) ON DELETE RESTRICT,
    joined_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_bundle_participant_bundle_member UNIQUE (bundle_id, member_id)
);

CREATE INDEX ix_bundle_participants_member_id
    ON bundle_participants(member_id);

CREATE TABLE bundle_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bundle_id BIGINT NOT NULL REFERENCES bundles(id) ON DELETE CASCADE,
    member_id BIGINT NOT NULL REFERENCES members(id) ON DELETE RESTRICT,
    content TEXT NOT NULL DEFAULT '',
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_bundle_comment_bundle_member UNIQUE (bundle_id, member_id),
    CONSTRAINT ck_bundle_comment_version_nonnegative CHECK (version >= 0),
    CONSTRAINT ck_bundle_comment_timestamps CHECK (updated_at >= created_at)
);

CREATE INDEX ix_bundle_comments_member_id
    ON bundle_comments(member_id);

CREATE TABLE bundle_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bunch_id BIGINT NOT NULL REFERENCES bunches(id) ON DELETE CASCADE,
    member_id BIGINT NOT NULL REFERENCES members(id) ON DELETE RESTRICT,
    operation VARCHAR(128) NOT NULL,
    request_key UUID NOT NULL,
    fingerprint VARCHAR(64) NOT NULL,
    -- This is intentionally not a foreign key: idempotency results survive bundle deletion.
    bundle_id BIGINT NOT NULL,
    revision BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_bundle_request_key UNIQUE (bunch_id, member_id, operation, request_key),
    CONSTRAINT ck_bundle_request_revision_nonnegative CHECK (revision >= 0)
);

CREATE INDEX ix_bundle_requests_bundle_id
    ON bundle_requests(bundle_id);
