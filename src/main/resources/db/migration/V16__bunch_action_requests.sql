CREATE TABLE bunch_action_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
    bunch_id BIGINT NOT NULL,
    actor_membership_id BIGINT NOT NULL,
    operation VARCHAR(32) NOT NULL,
    request_key UUID NOT NULL,
    fingerprint CHAR(64) NOT NULL,
    result JSONB NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_bunch_action_request_operation CHECK (
        operation IN ('PROFILE', 'OWNER_TRANSFER', 'LEAVE', 'DELETE')
    ),
    CONSTRAINT ck_bunch_action_request_result CHECK (jsonb_typeof(result) = 'object'),
    CONSTRAINT ck_bunch_action_request_expiration CHECK (expires_at > created_at),
    CONSTRAINT uk_bunch_action_request_key UNIQUE (member_id, bunch_id, operation, request_key)
);

CREATE INDEX ix_bunch_action_requests_expires
    ON bunch_action_requests(expires_at, id);
