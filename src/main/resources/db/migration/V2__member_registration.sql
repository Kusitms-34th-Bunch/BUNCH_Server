ALTER TABLE members
    ADD COLUMN signup_status VARCHAR(32) NOT NULL DEFAULT 'IN_PROGRESS'
        CHECK (signup_status IN ('IN_PROGRESS', 'COMPLETED')),
    ADD COLUMN account_status VARCHAR(32) NOT NULL DEFAULT 'ACTIVE'
        CHECK (account_status IN ('ACTIVE', 'SUSPENDED', 'WITHDRAWN')),
    ADD COLUMN nickname VARCHAR(120) COLLATE "C" UNIQUE,
    ADD COLUMN birth_year INTEGER,
    ADD COLUMN gender VARCHAR(16) CHECK (gender IN ('FEMALE', 'MALE')),
    ADD COLUMN image_public_id VARCHAR(255),
    ADD COLUMN image_url VARCHAR(255),
    ADD COLUMN completed_at TIMESTAMP WITH TIME ZONE,
    ADD COLUMN registration_fingerprint VARCHAR(64);

CREATE TABLE member_consents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
    type VARCHAR(32) NOT NULL CHECK (type IN ('SERVICE', 'PRIVACY', 'AGE_OVER_14', 'DEMOGRAPHICS')),
    version VARCHAR(100) NOT NULL,
    agreed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_member_consent UNIQUE (member_id, type, version)
);
