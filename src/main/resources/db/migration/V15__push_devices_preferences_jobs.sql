CREATE TABLE push_devices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    installation_id UUID NOT NULL UNIQUE,
    member_id BIGINT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
    session_id UUID NOT NULL,
    environment VARCHAR(16) NOT NULL,
    topic VARCHAR(120) NOT NULL,
    token_ciphertext BYTEA NOT NULL,
    token_hash CHAR(64) NOT NULL,
    authorization_status VARCHAR(20) NOT NULL,
    registered_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_push_devices_environment
        CHECK (environment IN ('SANDBOX', 'PRODUCTION')),
    CONSTRAINT ck_push_devices_authorization_status
        CHECK (authorization_status IN ('NOT_DETERMINED', 'DENIED', 'AUTHORIZED', 'PROVISIONAL')),
    CONSTRAINT ck_push_devices_token_hash
        CHECK (token_hash ~ '^[0-9a-f]{64}$')
);

CREATE UNIQUE INDEX uk_push_devices_environment_topic_token
    ON push_devices(environment, topic, token_hash);
CREATE INDEX ix_push_devices_member_session
    ON push_devices(member_id, session_id);

CREATE TABLE push_preferences (
    member_id BIGINT PRIMARY KEY REFERENCES members(id) ON DELETE CASCADE,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    types JSONB NOT NULL DEFAULT '{}'::jsonb,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_push_preferences_types_object
        CHECK (jsonb_typeof(types) = 'object')
);

CREATE TABLE push_jobs (
    id UUID PRIMARY KEY,
    device_id BIGINT REFERENCES push_devices(id) ON DELETE SET NULL,
    recipient_member_id BIGINT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
    session_id UUID NOT NULL,
    bunch_id BIGINT NOT NULL,
    notification_id BIGINT REFERENCES notifications(id) ON DELETE SET NULL,
    dedupe_key VARCHAR(200) NOT NULL,
    type VARCHAR(40) NOT NULL,
    payload JSONB NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    attempts INTEGER NOT NULL DEFAULT 0,
    available_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    sent_at TIMESTAMP WITH TIME ZONE,
    last_error_code VARCHAR(80),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_push_jobs_type
        CHECK (type IN (
            'DRAFT_PARTICIPANT_ADDED',
            'DRAFT_ACTIVITY',
            'COMMENT_REMINDER',
            'DRAFT_PARTICIPANT_REMOVED',
            'DRAFT_READY_TO_PUBLISH',
            'DRAFT_PARTICIPANTS_INSUFFICIENT',
            'BUNDLE_PUBLISHED',
            'CANDIDATE_CREATED',
            'CHARACTER_GROWN',
            'MEMBER_JOINED',
            'CO_OWNER_GRANTED',
            'CO_OWNER_REVOKED',
            'OWNER_TRANSFERRED',
            'MEMBER_REMOVED',
            'BUNCH_DELETED',
            'BUNCH_VISIBILITY_CHANGED',
            'BUNCH_FOLLOWED',
            'FOLLOW_REQUESTED',
            'FOLLOW_REQUEST_APPROVED',
            'SOCIAL_COMMENT_CREATED',
            'BUNDLE_LIKED'
        )),
    CONSTRAINT ck_push_jobs_status
        CHECK (status IN ('PENDING', 'SENT', 'FAILED', 'CANCELLED')),
    CONSTRAINT ck_push_jobs_attempts
        CHECK (attempts BETWEEN 0 AND 5),
    CONSTRAINT ck_push_jobs_payload_object
        CHECK (jsonb_typeof(payload) = 'object'),
    CONSTRAINT ck_push_jobs_expiration
        CHECK (expires_at > created_at),
    CONSTRAINT ck_push_jobs_sent_at
        CHECK ((status = 'SENT' AND sent_at IS NOT NULL) OR status <> 'SENT')
);

CREATE UNIQUE INDEX uk_push_jobs_recipient_device_dedupe
    ON push_jobs(recipient_member_id, device_id, dedupe_key);
CREATE INDEX ix_push_jobs_status_available_id
    ON push_jobs(status, available_at, id);
